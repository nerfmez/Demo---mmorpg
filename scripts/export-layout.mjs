writeFileSync(new URL('../data/generated/layout.json', import.meta.url), JSON.stringify(clean(out)));
const hf = world.heightfield;
writeFileSync(
  new URL('../data/generated/heightmap.json', import.meta.url),
  JSON.stringify({ _doc: 'Terrain height (metres) on a regular grid: height at (ox + i*res, oz + j*res) is data[j*w + i]. Godot: HeightMapShape3D / a MeshInstance3D.', ox: hf.ox, oz: hf.oz, res: hf.res, w: hf.w, h: hf.h, data: Array.from(hf.data, (v) => Math.round(v * 100) / 100) })
);
console.log(`heightmap: ${hf.w}x${hf.h} @ ${hf.res} m`);
console.log(`layout: ${world.circles.length} circles, ${world.boxes.length} boxes, ${out.spawns.length} spawns`);
